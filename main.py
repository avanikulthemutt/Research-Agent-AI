
from datetime import datetime

knowledge_base = {
    "artificial intelligence": (
        "Artificial Intelligence (AI) enables computers "
        "to perform tasks that normally require human intelligence. "
        "It is used in healthcare, education, robotics, and business."
    ),
    "machine learning": (
        "Machine Learning is a branch of AI that helps computers "
        "learn patterns from data and make predictions. "
        "It is used in recommendation systems and fraud detection."
    ),
    "cybersecurity": (
        "Cybersecurity protects computers, networks, and data "
        "from digital attacks. Common methods include encryption, "
        "firewalls, strong passwords, and multi-factor authentication."
    ),
    "climate change": (
        "Climate change refers to long-term changes in temperature "
        "and weather patterns. Human activities, especially burning "
        "fossil fuels, are a major cause of recent global warming."
    ),
    "education technology": (
        "Education technology uses digital tools to improve learning. "
        "Examples include online classrooms, learning apps, "
        "digital libraries, and AI-based tutoring systems."
    )
}


def research_agent(topic):
    topic = topic.strip().lower()

    print("\nResearch Agent AI")
    print("-" * 35)
    print("Topic:", topic.title())

    if topic in knowledge_base:
        result = knowledge_base[topic]
    else:
        result = (
            "No information is available for this topic in the "
            "current knowledge base. Try artificial intelligence, "
            "machine learning, cybersecurity, climate change, "
            "or education technology."
        )

    report = f"""
RESEARCH REPORT
===============

Topic: {topic.title()}
Date: {datetime.now().strftime("%d-%m-%Y")}

Research Findings:
{result}

Generated by: Research Agent AI
"""

    print("\nResearch Findings:")
    print(result)

    with open("research_report.txt", "w", encoding="utf-8") as file:
        file.write(report)

    print("\nReport saved as research_report.txt")


while True:
    topic = input(
        "\nEnter a research topic (or type 'exit' to stop): "
    )

    if topic.strip().lower() == "exit":
        print("Research Agent stopped.")
        break

    if topic.strip():
        research_agent(topic)
    else:
        print("Please enter a topic.")
